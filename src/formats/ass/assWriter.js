// AssLineContentBuilder

/** Marks a tag argument as a C# float (JS numbers are otherwise written as C# ints). */
export class Float {
  constructor(value) {
    this.value = value;
  }
}

export class AssLineContentBuilder {
  constructor() {
    this._pendingTags = '';
    this._content = '';
  }

  /** @param {string} tagName @param {...(boolean|number|Float|string|Color|AssStyle|null)} args numbers are ints */
  appendTag(tagName, ...args) {
    this._pendingTags += '\\' + tagName;
    if (args.length > 1) this._pendingTags += '(';

    args.forEach((arg, i) => {
      if (i > 0) this._pendingTags += ',';
      this._appendTagArgument(tagName, arg);
    });

    if (args.length > 1) this._pendingTags += ')';
  }

  _appendTagArgument(tagName, arg) {
    if (arg == null) return;

    if (typeof arg === 'boolean') this._pendingTags += arg ? '1' : '0';
    else if (typeof arg === 'number') {
      if (!Number.isInteger(arg)) throw new Error(`Tag argument ${arg} is not an int (wrap floats in Float)`);
      this._pendingTags += hasHexadecimalArgument(tagName) ? `&H${(arg >>> 0).toString(16).toUpperCase()}&` : String(arg);
    } else if (arg instanceof Float) this._pendingTags += formatFloat(arg.value);
    else if (typeof arg === 'string') this._pendingTags += arg;
    else if (arg instanceof Color) this._pendingTags += `&H${hex2(arg.b)}${hex2(arg.g)}${hex2(arg.r)}&`;
    else if (arg instanceof AssStyle) this._pendingTags += arg.name;
    else throw new Error('Not supported tag argument');
  }

  appendText(text) {
    if (text == null || text.length === 0) return;

    this._flushTags();

    text = text.replace(/\\([nNh])/g, '\\{}$1');
    text = text.replace(/\r\n/g, '\\N');
    text = text.replaceAll('\xA0', '\\h');
    this._content += text;
  }

  _flushTags() {
    if (this._pendingTags.length === 0) return;

    this._content += '{' + this._pendingTags + '}';
    this._pendingTags = '';
  }

  toString() {
    this._flushTags();
    return this._content;
  }
}

function hasHexadecimalArgument(tagName) {
  return tagName === '1a' || tagName === '2a' || tagName === '3a' || tagName === '4a';
}
