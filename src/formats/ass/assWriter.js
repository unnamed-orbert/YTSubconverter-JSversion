// Port of the writing part of Formats/Ass/AssDocument.cs (AssDocument(SubtitleDocument), Save,
// WriteHeader, WriteStyles, WriteLines, WriteLine...) and of AssLineContentBuilder.cs.
//
// VisualizingAssDocument (the "visual" .ass output, which needs font metrics from the OS) is not ported.

import { HorizontalTextDirection, OffsetType, RubyPart, ShadowType, VerticalTextType } from '../../enums.js';
import { Color } from '../../util/color.js';
import { f32, formatFloat, toInt } from '../../util/numbers.js';
import { AssLine, AssSection, AssStyle, getAlignment } from './assModel.js';
import { getHorizontalTextDirectionId, getVerticalTextTypeId } from './tags.js';

const EFFECT_NO_ANDROID_DARK_TEXT_HACK = 'no_android_dark_text_hack';

/**
 * Version written in the header. The C# code writes the version of the YTSubConverter.Shared assembly,
 * which declares none and therefore is 1.0.0.0.
 */
export const SCRIPT_GENERATOR_VERSION = '1.0.0';

// ---------------------------------------------------------------------------------------------
// AssDocument(SubtitleDocument doc)

/**
 * Builds an AssDocument with the built-in YT* styles (Resources.DefaultStyles) and the lines of `doc`.
 * @param {typeof import('./assDocument.js').AssDocument} AssDocumentClass
 * @param {import('../subtitleDocument.js').SubtitleDocument} doc
 * @param {string} defaultStylesAss
 * @param {import('./assModel.js').AssStyleOptions[]} defaultStyleOptions
 */
export function createAssDocumentFrom(AssDocumentClass, doc, defaultStylesAss, defaultStyleOptions) {
  const assDoc = new AssDocumentClass(defaultStylesAss, defaultStyleOptions);

  const sizeFactor = f32(doc.videoDimensions.height / assDoc.videoDimensions.height);
  for (const style of assDoc.styles) style.lineHeight = f32(style.lineHeight * sizeFactor);

  assDoc.videoDimensions = { ...doc.videoDimensions };

  assDoc.lines = doc.lines.map((l) => (l instanceof AssLine ? l : AssLine.from(l)));
  return assDoc;
}

// ---------------------------------------------------------------------------------------------
// Save

class TextWriter {
  constructor(newline) {
    this.newline = newline;
    this.parts = [];
  }

  write(text) {
    this.parts.push(text);
  }

  writeLine(text = '') {
    this.parts.push(text, this.newline);
  }

  toString() {
    return this.parts.join('');
  }
}

/**
 * AssDocument.Save.
 * @param {import('./assDocument.js').AssDocument} doc
 * @param {{bom?: boolean, newline?: string}} [options]
 *   bom: prepend a UTF-8 BOM, as the C# StreamWriter does (default false).
 *   newline: line terminator (default "\r\n", Environment.NewLine on Windows where the original runs).
 */
export function saveAssDocument(doc, { bom = false, newline = '\r\n' } = {}) {
  const writer = new TextWriter(newline);
  writeHeader(doc, writer);
  writeStyles(doc, writer);
  writeLines(doc, writer);
  return (bom ? '﻿' : '') + writer.toString();
}

function writeHeader(doc, writer) {
  writer.writeLine('[Script Info]');
  writer.writeLine(`; Script generated by YTSubConverter ${SCRIPT_GENERATOR_VERSION}`);
  writer.writeLine('; https://github.com/arcusmaximus/YTSubConverter/');
  writer.writeLine('ScriptType: v4.00+');
  writer.writeLine('WrapStyle: 0');
  writer.writeLine('ScaledBorderAndShadow: yes');
  writer.writeLine('PlayResX: ' + doc.videoDimensions.width);
  writer.writeLine('PlayResY: ' + doc.videoDimensions.height);
  writer.writeLine();
}

function writeStyles(doc, writer) {
  writer.writeLine('[V4+ Styles]');
  writer.writeLine(
    'Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, ' +
      'StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding',
  );
  for (const style of doc.styles) {
    writer.write('Style: ');
    writer.write(style.name + ',');
    writer.write(style.font + ',');
    writer.write(formatFloat(style.lineHeight) + ',');
    writer.write(styleColorToHex(style.primaryColor) + ',');
    writer.write(styleColorToHex(style.secondaryColor) + ',');
    writer.write(styleColorToHex(style.outlineColor) + ',');
    writer.write(styleColorToHex(style.shadowColor) + ',');
    writer.write((style.bold ? 1 : 0) + ',');
    writer.write((style.italic ? 1 : 0) + ',');
    writer.write((style.underline ? 1 : 0) + ',');
    writer.write('0,100,100,0,0,');
    writer.write((style.outlineIsBox ? 3 : 1) + ',');
    writer.write(formatFloat(style.outlineThickness) + ',');
    writer.write(formatFloat(style.shadowDistance) + ',');
    writer.write(getAlignment(style.anchorPoint) + ',');
    writer.write('25,25,15,1');
    writer.writeLine();
  }
  writer.writeLine();
}

const hex2 = (v) => v.toString(16).toUpperCase().padStart(2, '0');

function styleColorToHex(color) {
  return `&H${hex2(255 - color.a)}${hex2(color.b)}${hex2(color.g)}${hex2(color.r)}`;
}

function writeLines(doc, writer) {
  writer.writeLine('[Events]');
  writer.writeLine('Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text');

  for (const line of doc.lines) writeLine(doc, line, writer);
}

/** @param {AssLine} line */
function writeLine(doc, line, writer) {
  if (line.sections.length === 0) return;

  let style = requireStyle(getStyleMatchingStructure(doc, line.sections[0]), line.sections[0]);
  writeLineMetadata(line, style, writer);

  let prevSection = new AssSection();
  let prevStyle = style;
  doc.applyStyle(prevSection, prevStyle);

  const lineContent = new AssLineContentBuilder();
  appendLineTags(line, style, lineContent);

  let currentRubyPosition = RubyPart.None;
  for (let i = 0; i < line.sections.length; i++) {
    const section = line.sections[i];
    style = requireStyle(getStyleMatchingStructure(doc, section), section);
    if (style !== prevStyle || (currentRubyPosition !== RubyPart.None && section.rubyPart === RubyPart.None)) {
      lineContent.appendTag('r', style);
      currentRubyPosition = RubyPart.None;
      prevSection = prevSection.clone();
      doc.applyStyle(prevSection, style);
    }

    appendSectionTags(doc, section, prevSection, lineContent);

    if (section.rubyPart === RubyPart.Base) {
      let rubyPart;
      if (i + 4 > line.sections.length || ((rubyPart = line.sections[i + 2].rubyPart) !== RubyPart.TextBefore && rubyPart !== RubyPart.TextAfter))
        throw new Error('Invalid ruby sequence');

      if (rubyPart !== currentRubyPosition) {
        lineContent.appendTag('ytruby', rubyPart === RubyPart.TextBefore ? 8 : 2);
        currentRubyPosition = rubyPart;
      }
      lineContent.appendText(`[${section.text}/${line.sections[i + 2].text}]`);
      i += 3;
    } else {
      lineContent.appendText(section.text);
    }

    prevSection = section;
    prevStyle = style;
  }

  writer.writeLine(lineContent.toString());
}

/** In C# a missing style ends in a NullReferenceException; here we give a readable error instead. */
function requireStyle(style, section) {
  if (style == null) throw new Error(`No style matches the structure (background box/shadow types) of section "${section.text}"`);
  return style;
}

function writeLineMetadata(line, style, writer) {
  const effects = !line.androidDarkTextHackAllowed ? EFFECT_NO_ANDROID_DARK_TEXT_HACK : '';
  writer.write(`Dialogue: ${line.layer ?? 0},${formatTimestamp(line.start)},${formatTimestamp(line.end)},${style.name},,0,0,0,${effects},`);
}

const MS_PER_DAY = 86400000;
const pad2 = (v) => String(v).padStart(2, '0');

/** {(int)(time - TimeBase).TotalHours}:{time:mm\:ss\.ff} (time in ms relative to TimeBase, which is midnight). */
export function formatTimestamp(time) {
  const hours = toInt(time / 3600000);
  const timeOfDay = ((time % MS_PER_DAY) + MS_PER_DAY) % MS_PER_DAY;
  const minutes = Math.floor(timeOfDay / 60000) % 60;
  const seconds = Math.floor(timeOfDay / 1000) % 60;
  const centiseconds = Math.floor((timeOfDay % 1000) / 10);
  return `${hours}:${pad2(minutes)}:${pad2(seconds)}.${pad2(centiseconds)}`;
}

/** Finds the first style whose background box and shadow types match those of the section. */
function getStyleMatchingStructure(doc, section) {
  const sectionShadowTypes = new Set(section.shadowColors.keys());

  for (const style of doc.styles) {
    const options = doc.getStyleOptions(style);

    if (style.hasOutlineBox !== section.backColor.a > 0) continue;

    const styleShadowTypes = new Set();
    if (style.hasOutline && !style.outlineIsBox) styleShadowTypes.add(ShadowType.Glow);

    if (options != null) for (const type of options.shadowTypes) styleShadowTypes.add(type);

    if (!setEquals(styleShadowTypes, sectionShadowTypes)) continue;

    return style;
  }
  return null;
}

function setEquals(a, b) {
  if (a.size !== b.size) return false;
  for (const item of a) if (!b.has(item)) return false;
  return true;
}

function appendLineTags(line, style, lineContent) {
  if (line.anchorPoint !== style.anchorPoint) lineContent.appendTag('an', getAlignment(line.anchorPoint));

  if (line.position != null) lineContent.appendTag('pos', new Float(line.position.x), new Float(line.position.y));

  if (line.verticalTextType !== VerticalTextType.None)
    lineContent.appendTag('ytvert', getVerticalTextTypeId(line.horizontalTextDirection, line.verticalTextType));
  else if (line.horizontalTextDirection !== HorizontalTextDirection.LeftToRight)
    lineContent.appendTag('ytdir', getHorizontalTextDirectionId(line.horizontalTextDirection));
}

function appendSectionTags(doc, section, prevSection, lineContent) {
  if (section.font !== prevSection.font) lineContent.appendTag('fn', section.font);

  const prevLineHeight = scaleToLineHeight(doc, prevSection.font, prevSection.scale);
  const lineHeight = scaleToLineHeight(doc, section.font, section.scale);
  if (lineHeight !== prevLineHeight) lineContent.appendTag('fs', new Float(lineHeight));

  if (section.bold !== prevSection.bold) lineContent.appendTag('b', section.bold);

  if (section.italic !== prevSection.italic) lineContent.appendTag('i', section.italic);

  if (section.underline !== prevSection.underline) lineContent.appendTag('u', section.underline);

  appendColorTags('c', '1a', prevSection.foreColor, section.foreColor, lineContent);
  appendColorTags('2c', '2a', prevSection.secondaryColor, section.secondaryColor, lineContent);

  const firstShadowColor = (s) => s.shadowColors.values().next().value;
  if (section.backColor.a > 0) {
    appendColorTags('3c', '3a', prevSection.backColor, section.backColor, lineContent);
    if (prevSection.shadowColors.size === 1 && section.shadowColors.size === 1)
      appendColorTags('4c', '4a', firstShadowColor(prevSection), firstShadowColor(section), lineContent);
  } else if (prevSection.shadowColors.size === 1 && section.shadowColors.size === 1) {
    if (section.shadowColors.keys().next().value === ShadowType.Glow)
      appendColorTags('3c', '3a', firstShadowColor(prevSection), firstShadowColor(section), lineContent);
    else
      appendColorTags('4c', '4a', firstShadowColor(prevSection), firstShadowColor(section), lineContent);
  }

  if (section.offset !== prevSection.offset) {
    const tag = { [OffsetType.Subscript]: 'ytsub', [OffsetType.Superscript]: 'ytsup', [OffsetType.Regular]: 'ytsur' }[section.offset];
    if (tag === undefined) throw new Error(`Invalid offset type: ${section.offset}`);
    lineContent.appendTag(tag);
  }

  if (section.packed !== prevSection.packed) lineContent.appendTag('ytpack', section.packed);

  if (section.duration > 0) lineContent.appendTag('k', toInt(section.duration / 10));

  if (section.blur !== prevSection.blur) lineContent.appendTag('blur', new Float(section.blur));
}

/** AssDocument.ScaleToLineHeight (virtual in C#; only VisualizingAssDocument overrides it). */
function scaleToLineHeight(doc, font, scale) {
  return f32(doc.defaultStyle.lineHeight * scale);
}

function appendColorTags(colorTag, alphaTag, prevColor, newColor, lineContent) {
  if (prevColor.r !== newColor.r || prevColor.g !== newColor.g || prevColor.b !== newColor.b) lineContent.appendTag(colorTag, newColor);

  if (prevColor.a !== newColor.a) lineContent.appendTag(alphaTag, 255 - newColor.a);
}

