function newDocWithLine(build) {
  const doc = AssDocument.fromSubtitleDocument(new SrtDocument());
  const line = new AssLine(1000, 2000);
  build(line, doc);
  doc.lines.push(line);
  return doc;
}

/** A section formatted like the YTPlain style (no box, no shadows). */
function plainSection(doc, text) {
  const section = new AssSection(text);
  doc.applyStyle(section, doc.getStyle('YTPlain'));
  return section;
}

function lastLine(text) {
  return text.trimEnd().split('\r\n').at(-1);
}

test('SRT -> .ass: header, built-in styles and dialogue (CRLF)', () => {
  const srt = SrtDocument.parse('1\n00:00:01,000 --> 00:00:02,500\nOlá mundo\nlinha 2\n\n');
  const text = convertDocument(srt, '.ass').save();

  assert.ok(text.startsWith(EXPECTED_HEADER.join('\r\n') + '\r\n'));
  assert.ok(!text.replace(/\r\n/g, '').includes('\n'), 'only CRLF line terminators');
  assert.equal((text.match(/^Style: /gm) ?? []).length, 10);
  assert.ok(text.includes('\r\n\r\n[Events]\r\nFormat: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\r\n'));
  // SRT sections have no font and a background box: the C# code writes an empty \fn and picks YTPlainBox
  assert.equal(
    lastLine(text),
    'Dialogue: 0,0:00:01.00,0:00:02.50,YTPlainBox,,0,0,0,,{\\fn\\c&HFFFFFF&\\1a&H0&\\3c&H080808&\\3a&H3F&}Olá mundo\\Nlinha 2',
  );
});

test('save options: BOM and newline', () => {
  const doc = AssDocument.fromSubtitleDocument(new SrtDocument());
  assert.ok(doc.save({ bom: true }).startsWith('﻿[Script Info]\r\n'));
  assert.ok(doc.save({ newline: '\n' }).startsWith('[Script Info]\n; Script'));
});

test('style font sizes are scaled to the video height', () => {
  const srt = new SrtDocument();
  srt.videoDimensions = { width: 1920, height: 1080 };
  const text = AssDocument.fromSubtitleDocument(srt).save();
  assert.match(text, /PlayResX: 1920\r\nPlayResY: 1080\r\n/);
  assert.match(text, /\r\nStyle: YTPlain,Roboto,57,/);

  srt.videoDimensions = { width: 640, height: 480 };
  // 38 * (480 / 720f) in float32, written with 7 significant digits like .NET Framework
  assert.match(AssDocument.fromSubtitleDocument(srt).save(), /\r\nStyle: YTPlain,Roboto,25\.33333,/);
});

test('timestamps: hours are not wrapped, centiseconds are truncated', () => {
  assert.equal(formatTimestamp(0), '0:00:00.00');
  assert.equal(formatTimestamp(1999), '0:00:01.99');
  assert.equal(formatTimestamp(3723456), '1:02:03.45');
  assert.equal(formatTimestamp(100 * 3600000 + 5000), '100:00:05.00');
});

test('float formatting matches .NET Framework (G7)', () => {
  assert.equal(formatFloat(38), '38');
  assert.equal(formatFloat(Math.fround(0.01)), '0.01');
  assert.equal(formatFloat(Math.fround(1 / 3)), '0.3333333');
  assert.equal(formatFloat(-0), '0');
  assert.equal(formatFloat(12345678), '1.234568E+07');
  assert.equal(formatFloat(0.00001234), '1.234E-05');
});

test('AssLineContentBuilder: tag arguments and text escaping', () => {
  const b = new AssLineContentBuilder();
  b.appendTag('pos', new Float(Math.fround(640.5)), new Float(360));
  b.appendTag('b', true);
  b.appendTag('1a', 255 - 64);
  b.appendTag('c', Color.fromArgb(255, 0x12, 0x34, 0x56));
  b.appendTag('fn', null);
  b.appendTag('ytsub');
  b.appendText('a\\nb\\Nc\\hd\r\ne\xA0f');
  b.appendTag('i', false);
  b.appendText('');
  b.appendTag('u', true);
  b.appendText('g');
  assert.equal(b.toString(), '{\\pos(640.5,360)\\b1\\1a&HBF&\\c&H563412&\\fn\\ytsub}a\\{}nb\\{}Nc\\{}hd\\Ne\\hf{\\i0\\u1}g');

  const trailing = new AssLineContentBuilder();
  trailing.appendText('x');
  trailing.appendTag('k', 5);
  assert.equal(trailing.toString(), 'x{\\k5}');
});

test('line tags: alignment, position, text direction, effect and layer', () => {
  const doc = newDocWithLine((line, doc) => {
    line.layer = 3;
    line.anchorPoint = AnchorPoint.TopLeft;
    line.position = { x: Math.fround(100.25), y: 50 };
    line.horizontalTextDirection = 'RightToLeft';
    line.androidDarkTextHackAllowed = false;
    line.sections.push(plainSection(doc, 'texto'));
  });
  assert.equal(lastLine(doc.save()), 'Dialogue: 3,0:00:01.00,0:00:02.00,YTPlain,,0,0,0,no_android_dark_text_hack,{\\an7\\pos(100.25,50)\\ytdir4}texto');

  const vertical = newDocWithLine((line, doc) => {
    line.verticalTextType = 'Rotated';
    line.horizontalTextDirection = 'RightToLeft';
    line.sections.push(plainSection(doc, 'v'));
  });
  assert.equal(lastLine(vertical.save()), 'Dialogue: 0,0:00:01.00,0:00:02.00,YTPlain,,0,0,0,,{\\ytvert3}v');
});

test('section tags are written relative to the previous section; style switches use \\r', () => {
  const doc = newDocWithLine((line, doc) => {
    line.sections.push(plainSection(doc, 'a'));

    const bold = plainSection(doc, 'b');
    bold.bold = true;
    bold.scale = 2;
    bold.foreColor = Color.fromArgb(128, 255, 0, 0);
    bold.duration = 456;
    bold.blur = 1.5;
    line.sections.push(bold);

    const glow = new AssSection('c');
    doc.applyStyle(glow, doc.getStyle('YTGlow'));
    glow.shadowColors.set(ShadowType.Glow, Color.fromArgb(255, 0, 0, 255));
    line.sections.push(glow);
  });
  assert.equal(
    lastLine(doc.save()),
    'Dialogue: 0,0:00:01.00,0:00:02.00,YTPlain,,0,0,0,,a{\\fs76\\b1\\c&H0000FF&\\1a&H7F&\\k45\\blur1.5}b{\\rYTGlow\\3c&HFF0000&\\3a&H0&}c',
  );
});

test('ruby sections are written as [base/ruby]', () => {
  const doc = newDocWithLine((line, doc) => {
    const parts = [
      ['漢', RubyPart.Base],
      ['(', RubyPart.Parenthesis],
      ['かん', RubyPart.TextAfter],
      [')', RubyPart.Parenthesis],
      [' fim', RubyPart.None],
    ];
    for (const [text, rubyPart] of parts) {
      const section = plainSection(doc, text);
      section.rubyPart = rubyPart;
      line.sections.push(section);
    }
  });
  assert.equal(lastLine(doc.save()), 'Dialogue: 0,0:00:01.00,0:00:02.00,YTPlain,,0,0,0,,{\\ytruby2}[漢/かん]{\\rYTPlain} fim');

  const invalid = newDocWithLine((line, doc) => {
    const section = plainSection(doc, '漢');
    section.rubyPart = RubyPart.Base;
    line.sections.push(section);
  });
  assert.throws(() => invalid.save(), /Invalid ruby sequence/);
});

test('generic lines get \\k durations from their section start offsets', () => {
  const srt = SrtDocument.parse('1\n00:00:01,000 --> 00:00:02,000\nab\n\n');
  const [line] = srt.lines;
  const second = line.sections[0].clone();
  line.sections[0].text = 'a';
  second.text = 'b';
  second.startOffset = 300;
  line.sections.push(second);

  const ass = AssDocument.fromSubtitleDocument(srt);
  assert.deepEqual(ass.lines[0].sections.map((s) => s.duration), [300, 700]);
  assert.match(lastLine(ass.save()), /\\k30\}a\{\\k70\}b$/);
});

test('a section whose structure matches no style is an error', () => {
  const doc = newDocWithLine((line, doc) => {
    const section = plainSection(doc, 'x');
    section.shadowColors.set(ShadowType.Glow, Color.Black);
    section.shadowColors.set(ShadowType.SoftShadow, Color.Black);
    line.sections.push(section);
  });
  assert.throws(() => doc.save(), /No style matches/);
});

