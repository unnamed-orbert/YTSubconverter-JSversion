// Round trip with the files of the original project: X.ass -> lines -> AssDocument(doc) -> .ass text
// -> read again -> .ytt must give the same .ytt as converting X.ass directly.
// The C# reverse test (TestReverseConversion) starts from the .ytt files instead; see below.
//
// Excluded files, where the C# code behaves the same way:
// - Colors, Karaoke, Shadows, TextDirection, Transform: they have sections with several shadow types
//   (e.g. glow + soft shadow); no built-in YT* style has that structure (NullReferenceException in C#).
//   Lines read from .ytt never have this, which is why the C# reverse test passes for them.
// - SimultaneousReverse: "Collisions: Reverse" is not written to the .ass (lost in C# too).
const ROUND_TRIP_EXCLUDED = new Set(['Colors', 'Karaoke', 'Shadows', 'TextDirection', 'Transform', 'SimultaneousReverse']);
const styleOptions = loadStyleOptions(readFileSync(join(dir, 'StyleOptions.xml'), 'utf8'));

for (const file of readdirSync(dir).filter((f) => f.endsWith('.ass')).sort()) {
  const name = file.replace(/\.ass$/, '');
  if (ROUND_TRIP_EXCLUDED.has(name)) continue;

  test(`${name} (.ass -> .ass -> .ytt round trip)`, () => {
    const direct = new YttDocument(loadAssDocument(readFileSync(join(dir, file)), { styleOptions })).save();
    const written = AssDocument.fromSubtitleDocument(loadAssDocument(readFileSync(join(dir, file)), { styleOptions })).save();
    const roundTripped = new YttDocument(loadAssDocument(written)).save();
    assert.equal(roundTripped, direct);
  });
}

// ---------------------------------------------------------------------------------------------
// TestReverseConversion of the original project: X.ytt -> AssDocument -> .ass -> read -> .ytt must equal X.ytt
// (with timestamps rounded to frame centers). Needs the .ytt reader, which is developed separately.
const yttReader = typeof YttDocument.parse === 'function' ? (text) => YttDocument.parse(text) : null;

function roundYttTimestamps(xml) {
  return xml.replace(/<p t="(\d+)" d="(\d+)"/g, (_, t, d) => {
    const oldStart = Number(t);
    const oldEnd = oldStart + Number(d);
    // Special case: don't round t="1", an Android workaround of the YttDocument class
    const newStart = oldStart <= 1 ? oldStart : roundTimeToFrameCenter(oldStart);
    const newEnd = roundTimeToFrameCenter(oldEnd);
    return `<p t="${newStart}" d="${newEnd - newStart}"`;
  });
}

for (const file of readdirSync(dir).filter((f) => f.endsWith('.ytt')).sort()) {
  const name = file.replace(/\.ytt$/, '');
  test(`${name} (.ytt -> .ass -> .ytt, reverse)`, { skip: yttReader ? false : 'leitor de .ytt ainda não integrado' }, () => {
    const input = readFileSync(join(dir, file), 'utf8').replace(/^﻿/, '');
    const written = AssDocument.fromSubtitleDocument(yttReader(input)).save();
    const actual = new YttDocument(loadAssDocument(written)).save();
    assert.equal(actual, roundYttTimestamps(input));
  });
}
